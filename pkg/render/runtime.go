package render

import (
	"fmt"
	"strings"

	mcfgv1 "github.com/openshift/api/machineconfiguration/v1"

	"github.com/gilbahat/aix-machine-config-operator/pkg/rendered"
)

// runtimeResult is what the ContainerRuntimeConfigs contribute.
type runtimeResult struct {
	files []rendered.File
	// containerLogMaxSize is handed to the kubelet: with containerd the
	// kubelet rotates container logs (CRI-O's log_size_max has no
	// containerd equivalent).
	containerLogMaxSize string
}

// containerd log levels, which match CRI-O's names.
var containerdLogLevels = map[string]bool{"trace": true, "debug": true, "info": true, "warn": true, "error": true, "fatal": true, "panic": true}

// renderContainerRuntime maps ContainerRuntimeConfig fields onto
// containerd-aix. crcs is oldest first; later objects win, matching the MCO,
// which renders one MachineConfig per object and merges them in name order.
func renderContainerRuntime(crcs []*mcfgv1.ContainerRuntimeConfig) (runtimeResult, []string, error) {
	var (
		res      runtimeResult
		warnings []string
		logLevel string
	)
	for _, crc := range crcs {
		c := crc.Spec.ContainerRuntimeConfig
		if c == nil {
			continue
		}
		ignored := func(field string) {
			warnings = append(warnings, fmt.Sprintf("ContainerRuntimeConfig %s: %s has no effect on AIX nodes (containerd-aix, no cgroups)", crc.Name, field))
		}
		if c.LogLevel != "" {
			l := strings.ToLower(c.LogLevel)
			if !containerdLogLevels[l] {
				return res, nil, fmt.Errorf("ContainerRuntimeConfig %s: logLevel %q is not a containerd log level", crc.Name, c.LogLevel)
			}
			logLevel = l
		}
		if c.LogSizeMax != nil && !c.LogSizeMax.IsZero() {
			if c.LogSizeMax.Sign() < 0 {
				ignored("negative logSizeMax")
			} else {
				res.containerLogMaxSize = c.LogSizeMax.String()
			}
		}
		if c.PidsLimit != nil {
			ignored("pidsLimit")
		}
		if c.OverlaySize != nil && !c.OverlaySize.IsZero() {
			ignored("overlaySize")
		}
		if c.DefaultRuntime != "" {
			ignored("defaultRuntime")
		}
		if len(c.AdditionalLayerStores) > 0 || len(c.AdditionalImageStores) > 0 || len(c.AdditionalArtifactStores) > 0 {
			ignored("additional layer/image/artifact stores")
		}
	}
	if logLevel != "" {
		res.files = append(res.files, amcoFile(ContainerdDropInPath,
			"# Generated by the AIX Machine Config Operator from ContainerRuntimeConfig. Do not edit.\n"+
				"version = 3\n\n[debug]\n  level = "+tomlString(logLevel)+"\n",
			restartContainerd))
	}
	return res, warnings, nil
}
